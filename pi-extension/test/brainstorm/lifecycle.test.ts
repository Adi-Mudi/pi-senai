/**
 * Brainstorm lifecycle integration test (Phase 8)
 *
 * End-to-end coverage of the 8-phase brainstorm upgrade, wired through the
 * mocked command handlers. No real pi binary needed — this runs as part of
 * `npm test` (the e2e/ RPC harness is gated behind RUN_E2E=1).
 *
 * Steps verified:
 *   1. /senai-brainstorm refuses empty seed (Phase 2)
 *   2. /senai-brainstorm mints a brainstorm run id (Phase 1)
 *   3. The registry block surfaces in the stage prompt (Phase 3)
 *   4. Dispatcher accepts a scout-2 dispatch + strips Write tools (Phase 4)
 *   5. /senai-brainstorm-approve hard-rejects on _TBD_ placeholder (Phase 2)
 *   6. /senai-brainstorm-approve succeeds on a fully-filled brief (Phase 2)
 *   7. brainstorm-dispatch.md is written with the audit summary (Phase 5)
 *   8. /senai-doctor reads the audit log and surfaces findings (Phase 6)
 *   9. /senai-plan adopts the brainstorm run id (Phase 1)
 *  10. web-research agent is generated by /senai-generate-sub-agents (Phase 7.5)
 */

